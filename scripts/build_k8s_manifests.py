def postgres() -> None:
    """Generates PostgreSQL StatefulSet with persistent storage volume."""
    write(
        "10-postgres.yaml",
        f"""
apiVersion: v1
kind: Service
metadata:
  name: postgres
  namespace: {NS}
spec:
  clusterIP: None
  selector:
    app: postgres
  ports:
    - port: 5432
      targetPort: 5432
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: postgres
  namespace: {NS}
spec:
  serviceName: postgres
  replicas: 1
  selector:
    matchLabels:
      app: postgres
  template:
    metadata:
      labels:
        app: postgres
    spec:
      containers:
        - name: postgres
          image: postgres:16-alpine
          ports:
            - containerPort: 5432
          env:
            - name: POSTGRES_USER
              value: learnflow
            - name: POSTGRES_DB
              value: learnflow
            - name: POSTGRES_PASSWORD
              valueFrom:
                secretKeyRef:
                  name: learnflow-secrets
                  key: POSTGRES_PASSWORD
            - name: PGDATA
              value: /var/lib/postgresql/data/pgdata
          readinessProbe:
            exec:
              command: ["pg_isready", "-U", "learnflow", "-d", "learnflow"]
            initialDelaySeconds: 10
            periodSeconds: 5
          livenessProbe:
            exec:
              command: ["pg_isready", "-U", "learnflow"]
            initialDelaySeconds: 30
            periodSeconds: 15
{RESOURCES.format(cpu_req="100m", mem_req="256Mi", cpu_lim="1", mem_lim="1Gi")}          volumeMounts:
            - name: data
              mountPath: /var/lib/postgresql/data
  volumeClaimTemplates:
    - metadata:
        name: data
      spec:
        accessModes: ["ReadWriteOnce"]
        resources:
          requests:
            storage: 10Gi
""",
    )


def simple_service(
    name: str,
    image: str,
    port: int,
    storage: str,
    mount: str,
    probe: str,
    extra_env: str = "",
    command: str = "",
) -> str:
    """Helper generating deployment + service + PVC for simple stateful containers."""
    return f"""
apiVersion: v1
kind: Service
metadata:
  name: {name}
  namespace: {NS}
spec:
  selector:
    app: {name}
  ports:
    - port: {port}
      targetPort: {port}
---
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: {name}-data
  namespace: {NS}
spec:
  accessModes: ["ReadWriteOnce"]
  resources:
    requests:
      storage: {storage}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  namespace: {NS}
spec:
  replicas: 1
  strategy:
    type: Recreate
  selector:
    matchLabels:
      app: {name}
  template:
    metadata:
      labels:
        app: {name}
    spec:
      containers:
        - name: {name}
          image: {image}
          ports:
            - containerPort: {port}
{command}{extra_env}{probe}{RESOURCES.format(cpu_req="100m", mem_req="256Mi", cpu_lim="1", mem_lim="1Gi")}          volumeMounts:
            - name: data
              mountPath: {mount}
      volumes:
        - name: data
          persistentVolumeClaim:
            claimName: {name}-data
"""


def redis() -> None:
    """Generates Redis Deployment with append-only persistence."""
    probe = """          readinessProbe:
            exec:
              command: ["redis-cli", "ping"]
            initialDelaySeconds: 5
            periodSeconds: 5
"""
    command = '          args: ["redis-server", "--appendonly", "yes"]\n'
    write(
        "11-redis.yaml",
        simple_service("redis", "redis:7-alpine", 6379, "5Gi", "/data", probe, command=command),
    )


def chromadb() -> None:
    """Generates ChromaDB vector database deployment."""
