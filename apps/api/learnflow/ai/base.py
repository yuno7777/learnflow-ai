"""Provider-agnostic AI interfaces, protocols, and completion data structures.

===============================================================================
WHAT THIS FILE IS RESPONSIBLE FOR:
===============================================================================
This file defines the abstract contract that decouples the rest of the application
from specific AI vendors (OpenAI, Azure, Ollama, HuggingFace, Mock):
1. `ChatMessage`: Standardized message format (`role`, `content`, `tool_call_id`).
2. `ToolCall`: Standardized representation of an assistant tool/function invocation.
3. `Completion`: Unified response dataclass containing generated text, token counts,
   model name, finish reason, and parsed tool calls.
4. `EmbeddingResult`: Multi-vector container returned by embedding providers.
5. `ProviderUnavailable` & `ProviderRateLimited`: Exception types signaling the
   central AI Gateway to retry with exponential backoff or switch to a fallback provider.
6. `LLMProvider` & `EmbeddingProvider`: Python typing `Protocols` implemented by all adapters.

===============================================================================
WHY THIS DESIGN MATTERS (Software Design Pattern):
===============================================================================
This implements the **Adapter Pattern**. No service, router, or background task
in LearnFlow calls `openai.OpenAI()` directly. Everything talks exclusively to
the `LLMProvider` protocol via the central `AIGateway` (`ai/gateway.py`).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable


@dataclass(slots=True)
class ChatMessage:
    """A single chat message in an LLM conversation history.

    Attributes:
        role: Message author role ("system" | "user" | "assistant" | "tool").
        content: Text content of the message.
        tool_call_id: If role is "tool", links the result back to the tool invocation ID.
        name: Function name if providing tool output.
    """

    role: str
    content: str
    tool_call_id: str | None = None
    name: str | None = None

    def to_api(self) -> dict[str, Any]:
        """Serializes the message into the standard OpenAI-compatible JSON dict format."""
        msg: dict[str, Any] = {"role": self.role, "content": self.content}
        if self.tool_call_id:
            msg["tool_call_id"] = self.tool_call_id
        if self.name:
            msg["name"] = self.name
        return msg


@dataclass(slots=True)
class ToolCall:
    """Represents a tool/function call requested by the model during multi-turn assistant chat."""

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass(slots=True)
class Completion:
    """Normalized response payload returned by any LLM provider adapter.

    Attributes:
        text: The primary completion text generated by the model.
        model: Exact model name that produced this completion (e.g. "gpt-4o-mini").
        provider: Provider identifier string (e.g. "openai", "azure_openai", "ollama", "mock").
        input_tokens: Prompt token count reported by provider (or estimated).
        output_tokens: Completion token count reported by provider.
        finish_reason: Generation stop reason ("stop" | "length" | "tool_calls").
        tool_calls: List of structured function calls requested by the model.
        raw: Full raw provider API response dictionary for debugging.
    """

    text: str
    model: str
    provider: str
    input_tokens: int = 0
    output_tokens: int = 0
    finish_reason: str = "stop"
    tool_calls: list[ToolCall] = field(default_factory=list)
    raw: dict[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class EmbeddingResult:
    """Batch embedding vectors and token usage returned by an embedding provider."""

    vectors: list[list[float]]
    model: str
    provider: str
    input_tokens: int = 0


# -----------------------------------------------------------------------------
# Gateway Exceptions
# -----------------------------------------------------------------------------


class ProviderUnavailable(Exception):
    """Transient upstream error (e.g. 502, network timeout, or connection reset).

    Tells `AIGateway` to attempt retries before switching to the configured fallback provider.
    """


class ProviderRateLimited(ProviderUnavailable):
    """Upstream 429 Too Many Requests error with optional `Retry-After` header value."""

    def __init__(self, message: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


# -----------------------------------------------------------------------------
# Provider Protocols
# -----------------------------------------------------------------------------


@runtime_checkable
class LLMProvider(Protocol):
    """Protocol for text generation model adapters (OpenAI, Azure, Ollama, Mock)."""

    name: str

    async def complete(
        self,
        messages: list[ChatMessage],
        *,
        model: str,
        temperature: float = 0.2,
        max_tokens: int = 2048,
        json_schema: dict[str, Any] | None = None,
        tools: list[dict[str, Any]] | None = None,
    ) -> Completion: ...


@runtime_checkable
class EmbeddingProvider(Protocol):
    """Protocol for dense vector embedding adapters."""

    name: str
    dimensions: int

    async def embed(self, texts: list[str], *, model: str) -> EmbeddingResult: ...
